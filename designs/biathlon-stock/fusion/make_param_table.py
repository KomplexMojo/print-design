"""Regenerate PARAMETERS.md from the registry in stock_params.py.

    python3 make_param_table.py [fit.json]      # default: samples/fit-sample.json
"""

import sys
from pathlib import Path

import stock_params as sp

HERE = Path(__file__).parent


def main(argv):
    fit = Path(argv[0]) if argv else HERE / "samples" / "fit-sample.json"
    doc = sp.load_fit(fit)
    res = sp.resolve(doc, sp.printer_fits(sp.repo_root()))
    rows = res.by_name()
    cad = doc.get("cad_parameters") or {}
    alias = {v: k for k, v in sp.CAD_ALIASES.items()}

    out = ["# biathlon-stock: Fusion 360 parameter table", "",
           "Generated by `make_param_table.py` from `stock_params.py` (the registry is the source of truth;",
           f"edit it, not this file). Sample values from `{fit.relative_to(HERE) if fit.is_relative_to(HERE) else fit.name}`.", "",
           "Status: **measured** = straight from a measurement or rifle field, **derived** = expression of",
           "other parameters, **estimate** = a measurement feeds it but the rule is still a design input",
           "(part.py default used), **fixed** = design, hardware or printer constant, **check** = must stay ≥ 0.", "",
           "## 1. Measurements (`m_*`) and rifle (`r_*`)", "",
           "One parameter per numeric value in the JSON. S and T (sides) are not parameters; they set `face_side`.", "",
           "| JSON field | Fusion name | Unit | Sample |", "|---|---|---|---|"]
    for letter, m in doc["measurements"].items():
        if letter in sp.SIDE_LETTERS:
            out.append(f"| `measurements.{letter}` ({m['name']}) | (sets `face_side`) | | {m['value']} |")
            continue
        name = f"m_{letter}"
        r = rows.get(name)
        out.append(f"| `measurements.{letter}` ({m['name']}) | `{name}` | {m['unit']} | {r.expression if r else '(not created: no value)'} |")
    for key, (name, unit) in sp.RIFLE_PARAMS.items():
        r = rows.get(name)
        out.append(f"| `rifle.{key}` | `{name}` | {unit or '—'} | {r.expression if r else '(not created: no value)'} |")

    groups = [("switch", "2. Handedness switches"), ("fit", "3. Athlete fit"), ("reference", "4. Current-rifle reference"),
              ("stock", "5. Stock body"), ("hardware", "6. Hardware (placeholders until measured)"),
              ("holder", "7. Spare-magazine holder"), ("marking", "8. IBU marking surface"),
              ("joints", "9. Splits and joints"), ("derived", "10. Derived, shared by the components"),
              ("fits", "11. Printer fits (`printer/h2s.yaml`)"), ("ibu", "12. IBU limits"),
              ("check", "13. Checks (every `chk_*` must be ≥ 0)")]
    for g, title in groups:
        out += ["", f"## {title}", "",
                "| Fusion name | JSON `cad_parameters` key | Unit | Expression | Sample | Status | IBU | Note |",
                "|---|---|---|---|---|---|---|---|"]
        for p in sp.REGISTRY:
            if p.group != g:
                continue
            r = rows[p.name]
            key = alias.get(p.name, p.name)
            key = f"`{key}`" if key in cad else ""
            expr = r.expression if r.status != "estimate" else f"{r.expression} (target: `{p.expr}`)" if p.expr else r.expression
            src = f" Sources: {', '.join(p.sources)}." if p.sources else ""
            out.append(f"| `{p.name}` | {key} | {p.unit or '—'} | `{expr}` | {r.value:g} | {r.status} | {p.ibu} | {p.note}{src} |")

    unmapped = [k for k in cad if k not in sp.BY_NAME and k not in sp.CAD_ALIASES]
    out += ["", "## Fit-app keys with no Fusion row", ""]
    out += [f"- `{k}`" for k in unmapped] or ["None: every `cad_parameters` key maps to a row."]
    (HERE / "PARAMETERS.md").write_text("\n".join(out) + "\n", encoding="utf-8")
    print(f"wrote PARAMETERS.md ({len(sp.REGISTRY)} registry rows, {len(res.rows)} parameters for this record)")


if __name__ == "__main__":
    main(sys.argv[1:])
